proc isAsciiUpper(ch: char): bool =
  ch in {'A' .. 'Z'}

proc isAsciiLower(ch: char): bool =
  ch in {'a' .. 'z'}

proc isAsciiLetterOrDigit(ch: char): bool =
  ch in {'a' .. 'z', 'A' .. 'Z', '0' .. '9'}

proc lowerAscii(ch: char): char =
  if isAsciiUpper(ch):
    chr(ord(ch) + 32)
  else:
    ch

proc splitWords(value: string): seq[string] =
  var current = ""
  for ch in value:
    if isAsciiLetterOrDigit(ch):
      if isAsciiUpper(ch) and current.len > 0 and isAsciiLower(current[^1]):
        result.add(current)
        current = ""
      current.add(lowerAscii(ch))
    elif current.len > 0:
      result.add(current)
      current = ""
  if current.len > 0:
    result.add(current)

proc requireWords(value: string; subject: string): seq[string] =
  result = splitWords(value)
  if result.len == 0:
    raise newException(ValueError, subject & " cannot be empty")

proc joinPascal(words: seq[string]): string =
  for word in words:
    result.add(word.capitalizeAscii())

proc toPascalCase*(value: string): string =
  joinPascal(requireWords(value, "Identifier"))

proc toCamelCase*(value: string): string =
  result = toPascalCase(value)
  if result.len > 0:
    result[0] = lowerAscii(result[0])

proc toSnakeCase*(value: string): string =
  requireWords(value, "Identifier").join("_")

proc toKebabCase*(value: string): string =
  requireWords(value, "Identifier").join("-")

proc projectIdentity(destination: string): ProjectIdentity =
  let baseName = lastPathPart(destination)
  let words = requireWords(baseName, "Project name")
  result.packageName = words.join("_")
  result.titleName = joinPascal(words)
  result.slug = words.join("-")

proc applyPlaceholders(content: string; replacements: openArray[Placeholder]): string =
  result = content
  for replacement in replacements:
    result = result.replace(replacement.key, replacement.value)

proc scaffoldFile(relativePath: string; content: string): ScaffoldFile =
  ScaffoldFile(relativePath: relativePath, content: content)

proc writeScaffoldFiles(baseDir: string; files: seq[ScaffoldFile]) =
  for file in files:
    let target = baseDir / file.relativePath
    let targetDir = parentDir(target)
    if targetDir.len > 0 and not dirExists(targetDir):
      createDir(targetDir)
    if fileExists(target) or dirExists(target):
      raise newException(IOError, "Refusing to overwrite existing path: " & target)
    writeFile(target, file.content)

proc ensureFreshDirectory(destination: string) =
  if fileExists(destination) or dirExists(destination):
    raise newException(IOError, "Destination already exists: " & destination)
  createDir(destination)

