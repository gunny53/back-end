proc createStarterProject*(starter: string; destination: string) =
  let identity = projectIdentity(destination)
  let starterKey = starter.toLowerAscii()
  let files =
    case starterKey
    of "rest-api": restStarterFiles(identity)
    of "auth-jwt": authStarterFiles(identity)
    of "microservice": microserviceStarterFiles(identity)
    of "modular-monolith": modularMonolithStarterFiles(identity)
    else:
      raise newException(ValueError, "Unsupported starter: " & starter)

  ensureFreshDirectory(destination)
  writeScaffoldFiles(destination, files)

proc generateModule*(name: string; root: string = getCurrentDir()) =
  let moduleName = toPascalCase(name)
  let moduleSnake = toSnakeCase(name)
  let replacements = [
    (key: "__CONTROLLER_NAME__", value: moduleName & "Controller"),
    (key: "__MODULE_CONST__", value: moduleName & "Module"),
    (key: "__ROUTE_NAME__", value: toKebabCase(name))
  ]

  let files = @[
    scaffoldFile("src/apps/" & moduleSnake & "/main.nim", applyPlaceholders(generatedModuleControllerTemplate, replacements)),
    scaffoldFile("src/apps/" & moduleSnake & "/module.nim", applyPlaceholders(generatedModuleDescriptorTemplate, replacements))
