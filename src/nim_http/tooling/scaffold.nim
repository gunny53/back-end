    (key: "__resourceProcPrefix__", value: toCamelCase(name)),
    (key: "__CONTROLLER_NAME__", value: resourceName & "Controller"),
    (key: "__MODULE_CONST__", value: resourceName & "Module"),
    (key: "__ROUTE_NAME__", value: toKebabCase(name)),
